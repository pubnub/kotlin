package com.pubnub.docs.support.tools

import com.google.gson.GsonBuilder
import com.google.gson.JsonParser
import com.pubnub.docs.support.Tier
import java.io.File

/**
 * Coverage manifest of the live tier: `coverage.json`, generated, one entry per snippet id per file, keyed by the path of
 * the file relative to the repository root. `mode` is `live` (a test runs it) or `compile-only` (a method with
 * `@CompileOnly`). `snippet-map` maps every golden `<old docs module path>#<id>` to the new `<file>#<id>` that holds the
 * region now, which is what [Equivalence] compares.
 *
 * `LIVE_MANIFEST_WRITE=1` regenerates the file, otherwise [check] fails when it is stale. Things the docs embed that are
 * deliberately not run are in `snippet-exceptions.json` (hand maintained, shape checked by [checkExceptions]).
 */
object Manifest {
    private const val COMMENT =
        "GENERATED by the offline tests (DocsToolsTest) from the markers in com/pubnub/docs. DO NOT EDIT. Regenerate with " +
            "LIVE_MANIFEST_WRITE=1 scripts/dev/docs-snippets.sh lint. One entry per snippet id per file. " +
            "Deliberate exceptions live in snippet-exceptions.json."

    val coverageFile: File get() = Tier.file("coverage.json")
    val exceptionsFile: File get() = Tier.file("snippet-exceptions.json")

    private val gson = GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create()

    /** Returns the manifest as a tree of maps and the problems found while building it. */
    @JvmStatic
    @JvmOverloads
    fun build(
        files: List<SnippetScan.ScannedFile> = SnippetScan.scan(),
        goldens: Map<String, Goldens.Golden> = Goldens.load(),
    ): Pair<Map<String, Any>, List<String>> {
        val problems = mutableListOf<String>()
        val entries = sortedMapOf<String, MutableMap<String, Map<String, String>>>()
        val map = sortedMapOf<String, String>()
        for (snippet in SnippetScan.snippets(files)) {
            val file = snippet.file
            val at = "${file.rel}:${snippet.region.startLine}"
            val byId = entries.getOrPut(file.rel) { sortedMapOf() }
            if (snippet.id in byId) {
                problems.add("$at: duplicate snippet id \"${snippet.id}\", left out")
                continue
            }
            val entry = linkedMapOf<String, String>()
            when (snippet.owner) {
                "none" -> {
                    problems.add("$at: snippet \"${snippet.id}\" is not run by any test, left out")
                    continue
                }
                "compile-only" -> {
                    entry["mode"] = "compile-only"
                    entry["reason"] = snippet.holder?.compileOnly.orEmpty()
                }
                "sample" -> {
                    val runner = SnippetScan.samplesRunners(files, file).firstOrNull()
                    if (runner == null) {
                        problems.add("$at: \"Main\" sample snippet \"${snippet.id}\" is not run by any test, left out")
                        continue
                    }
                    entry["test"] = "${runner.first.rel.substringAfter("/com/pubnub/docs/")}::${runner.second.name}"
                    entry["role"] = SnippetScan.rolesIn(runner.first.slice(runner.second.declLine, runner.second.endLine)).joinToString(",")
                    entry["mode"] = "live"
                }
                else -> {
                    entry["test"] = snippet.testId.orEmpty()
                    val roles = SnippetScan.rolesIn(file.slice(snippet.test!!.declLine, snippet.test.endLine))
                    entry["role"] = roles.joinToString(",")
                    entry["mode"] = "live"
                }
            }
            if (entry["role"].isNullOrEmpty()) {
                entry.remove("role")
            }
            byId[snippet.id] = entry

            val origin = snippet.region.origin
            val candidates =
                if (origin != null) {
                    listOf(origin).filter { it in goldens }.ifEmpty {
                        problems.add("$at: origin $origin of snippet \"${snippet.id}\" is not a golden")
                        emptyList()
                    }
                } else {
                    goldens.filter { it.value.docset == file.docset && it.key.substringAfter('#') == snippet.id }.keys.toList()
                }
            if (candidates.size > 1) {
                val hint = "add a line \"// origin: <old path>#<id>\" above the start marker"
                problems.add("$at: snippet \"${snippet.id}\" matches ${candidates.size} goldens, $hint")
            } else if (candidates.size == 1) {
                map[candidates[0]] = "${file.rel}#${snippet.id}"
            }
        }
        val manifest =
            linkedMapOf<String, Any>(
                "\$comment" to COMMENT,
                "files" to entries.filterValues { it.isNotEmpty() },
                "whole_files" to emptyMap<String, Any>(),
                "snippet-map" to map,
            )
        return manifest to problems
    }

    @JvmStatic
    fun serialize(manifest: Map<String, Any>): String = gson.toJson(manifest) + "\n"

    /** The totals as a summary line. */
    @JvmStatic
    fun summary(manifest: Map<String, Any>): String {
        @Suppress("UNCHECKED_CAST")
        val files = manifest["files"] as Map<String, Map<String, Map<String, String>>>
        val all = files.values.flatMap { it.values }
        return "${all.size} snippets (live ${all.count { it["mode"] == "live" }}, compile-only ${all.count { it["mode"] == "compile-only" }}) in ${files.size} files"
    }

    /**
     * Compares the committed file with a fresh build. With `LIVE_MANIFEST_WRITE=1` it writes the file instead. Returns the
     * problems, empty when the manifest is up to date.
     */
    @JvmStatic
    fun check(
        build: Pair<Map<String, Any>, List<String>> = build(),
        write: Boolean = System.getenv("LIVE_MANIFEST_WRITE") == "1",
    ): List<String> {
        val (manifest, problems) = build
        val text = serialize(manifest)
        val out = problems.toMutableList()
        if (write) {
            coverageFile.writeText(text)
            println("manifest: wrote coverage.json, ${summary(manifest)}")
        } else if (!coverageFile.isFile || coverageFile.readText() != text) {
            out.add("coverage.json is stale. Run: LIVE_MANIFEST_WRITE=1 scripts/dev/docs-snippets.sh lint")
        } else {
            println("manifest: coverage.json is up to date, ${summary(manifest)}")
        }
        return out
    }

    /** The parsed coverage.json, or an empty manifest. */
    @JvmStatic
    fun read(): com.google.gson.JsonObject {
        val text =
            if (coverageFile.isFile) {
                coverageFile.readText()
            } else {
                """{"files":{},"whole_files":{},"snippet-map":{}}"""
            }
        return JsonParser.parseString(text).asJsonObject
    }

    /** Shape check of the hand maintained exceptions file. */
    @JvmStatic
    fun checkExceptions(file: File = exceptionsFile): List<String> {
        val problems = mutableListOf<String>()
        if (!file.isFile) {
            return listOf("snippet-exceptions.json is missing")
        }
        val root = JsonParser.parseString(file.readText()).asJsonObject
        val seen = mutableSetOf<Pair<String?, String>>()
        root.getAsJsonArray("exceptions")?.forEachIndexed { index, element ->
            val entry = element.asJsonObject
            val path = entry.get("path")?.takeIf { it.isJsonPrimitive }?.asString
            val where = "snippet-exceptions.json entry ${index + 1} (${path ?: "?"})"
            if (path.isNullOrBlank()) {
                problems.add("$where: \"path\" is required")
            }
            if ((entry.get("reason")?.takeIf { it.isJsonPrimitive }?.asString?.trim()?.length ?: 0) < 10) {
                problems.add("$where: \"reason\" is required (at least 10 characters)")
            }
            val ids = entry.get("ids")
            val badIds = ids != null && (!ids.isJsonArray || ids.asJsonArray.size() == 0 || ids.asJsonArray.any { !it.isJsonPrimitive })
            if (badIds) {
                problems.add("$where: \"ids\" must be a non-empty list of strings, or absent")
            }
            val idList = ids?.takeIf { it.isJsonArray && !badIds }?.asJsonArray?.map { it.asString } ?: listOf("*")
            for (id in idList) {
                if (!seen.add(path to id)) {
                    problems.add("$where: $id is listed twice")
                }
            }
        } ?: problems.add("snippet-exceptions.json: \"exceptions\" must be a list")
        root.getAsJsonArray("one_sided")?.forEachIndexed { index, element ->
            val entry = element.asJsonObject
            val where = "snippet-exceptions.json one_sided entry ${index + 1}"
            if (entry.get("docset")?.asString !in setOf("kotlin", "java") || entry.get("page")?.takeIf { it.isJsonPrimitive } == null) {
                problems.add("$where: needs \"docset\" (kotlin or java) and \"page\"")
            }
            if ((entry.get("reason")?.takeIf { it.isJsonPrimitive }?.asString?.trim()?.length ?: 0) < 10) {
                problems.add("$where: \"reason\" is required")
            }
        } ?: problems.add("snippet-exceptions.json: \"one_sided\" must be a list")
        return problems
    }
}
